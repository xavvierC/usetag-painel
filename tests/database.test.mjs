import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';
const A='00000000-0000-4000-8000-000000000001';const B='00000000-0000-4000-8000-000000000002';
const S='00000000-0000-4000-8000-000000000003';const T='00000000-0000-4000-8000-000000000004';
test('migration and financial/RLS contracts on local PostgreSQL engine',async()=>{
 const db=new PGlite();
 try{
  await db.exec(`create role anon;create role authenticated;create role service_role bypassrls;create schema auth;create table auth.users(id uuid primary key);
   create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid;$$;
   grant usage on schema auth to authenticated,anon;
   create schema storage;create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
   create table storage.objects(id uuid primary key default gen_random_uuid(),bucket_id text,name text);alter table storage.objects enable row level security;
   insert into auth.users values('${A}'),('${B}');`);
  await db.exec(await readFile(new URL('../supabase/migrations/20261023210746_panel_core.sql',import.meta.url),'utf8'));
  await db.exec(`set role authenticated;set request.jwt.claim.sub='${A}'`);
  const command=async(p,k=crypto.randomUUID())=>db.query('select public.panel_command($1::jsonb,$2::uuid)',[JSON.stringify(p),k]);
  const sale={action:'sale.save',id:S,client:'Cliente Fictício A',amountCents:29900,soldOn:'2026-10-23',status:'approved',version:1,items:[{model:'google',color:'blue',quantity:15,isGift:false}]};
  const key=crypto.randomUUID();await command(sale,key);await command(sale,key);
  assert.equal((await db.query('select count(*) n from sales')).rows[0].n,1);
  await assert.rejects(()=>command({...sale,amountCents:1},key));
  await command({...sale,id:T,client:'Cliente Fictício B',amountCents:55380});
  assert.equal(Number((await db.query('select sum(amount_cents) n from sales')).rows[0].n),85280);
  assert.equal(Number((await db.query('select sum(entitlement_cents) n from commissions')).rows[0].n),4264);
  const payment={action:'payment.create',amountCents:3000,date:'2026-10-23',allocations:[{saleId:S,amountCents:1000},{saleId:T,amountCents:2000}]};const pk=crypto.randomUUID();await command(payment,pk);await command(payment,pk);
  assert.equal(Number((await db.query('select count(*) n from financial_transactions')).rows[0].n),1);
  assert.equal(Number((await db.query('select sum(amount_cents) n from financial_transactions')).rows[0].n),3000);
  await assert.rejects(()=>command({...payment,amountCents:500,allocations:[{saleId:S,amountCents:500}]}));
  await assert.rejects(()=>command({...payment,amountCents:1,allocations:[{saleId:S,amountCents:2}]}));
  assert.equal(Number((await db.query('select count(*) n from commission_payments')).rows[0].n),1);
  await command({action:'sale.archive',id:S,version:1,archived:true});
  assert.equal(Number((await db.query('select entitlement_cents n from commissions where sale_id=$1',[S])).rows[0].n),1495);
  await command({...sale,version:3,status:'cancelled'});await command({...sale,version:4,status:'cancelled'});
  const history=(await db.query("select metadata from audit_logs where entity_id=$1 and metadata->'after'->>'payment_status'='cancelled'",[S])).rows;
  assert.ok(history.length>=1);assert.equal(history[0].metadata.after.entitlement_cents,0);assert.ok(!JSON.stringify(history).includes('Cliente Fictício'));
  assert.equal(Number((await db.query("select sum(amount_cents) n from commission_adjustments where status='unresolved'")).rows[0].n),1000);
  assert.equal(Number((await db.query('select sum(amount_cents) n from financial_transactions')).rows[0].n),3000);
  await command({action:'profile.save',name:'Exemplo',rateBps:1000});
  assert.equal(Number((await db.query('select commission_rate_bps n from sales where id=$1',[T])).rows[0].n),500);
  const imported={action:'import.run',importKey:crypto.randomUUID(),sales:[{client:'Importação fictícia A',amountCents:29900,soldOn:'2026-10-23',status:'approved',items:sale.items},{client:'Importação fictícia B',amountCents:55380,soldOn:'2026-10-23',status:'approved',items:sale.items}],goal:{name:'Meta de teste',amountCents:300000,startsOn:'2026-10-23',endsOn:'2026-10-28'}};
  await command(imported);await command(imported);
  assert.equal(Number((await db.query('select count(*) n from sales')).rows[0].n),4);
  assert.equal(Number((await db.query("select sum(entitlement_cents) n from commissions c join sales s on s.id=c.sale_id join clients l on l.id=s.client_id where l.name like 'Importação fictícia%'")).rows[0].n),4264);
  assert.equal(Number((await db.query('select rate_bps n from profiles')).rows[0].n),1000);
  await assert.rejects(()=>command({...imported,sales:[...imported.sales,{...imported.sales[0],amountCents:0}],importKey:crypto.randomUUID()}));
  assert.equal(Number((await db.query('select count(*) n from sales')).rows[0].n),4);
  await assert.rejects(()=>db.query('update commissions set entitlement_cents=999999'));
  await assert.rejects(()=>db.query("insert into audit_logs(owner_id,actor_id,entity,event)values($1,$1,'fake','fake')",[A]));
  await db.exec(`set request.jwt.claim.sub='${B}'`);
  assert.equal(Number((await db.query('select count(*) n from sales')).rows[0].n),0);
  assert.equal(Number((await db.query('select count(*) n from commissions')).rows[0].n),0);
  await assert.rejects(()=>command({action:'sale.archive',id:T,version:1,archived:true}));
  await assert.rejects(()=>command({...payment,amountCents:1,allocations:[{saleId:T,amountCents:1}]}));
  for(let i=0;i<15;i++)assert.equal((await db.query('select public.consume_panel_ai_budget() allowed')).rows[0].allowed,true);
  assert.equal((await db.query('select public.consume_panel_ai_budget() allowed')).rows[0].allowed,false);
  await db.exec("set role anon;set request.jwt.claim.sub=''");
  await assert.rejects(()=>db.query('select * from sales'));
  await assert.rejects(()=>command(sale));
 }finally{await db.close();}
});
